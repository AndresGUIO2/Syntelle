import json
import os
from pathlib import Path

import numpy as np
import pytest

from app.core.paths import ROOT
from app.preparation.neck_rig import project, validate
from app.preparation.projection_rig import unproject

PREPARED = Path(os.environ.get('SYNTELLE_NECK_PREPARED', str(ROOT/'.tools/neck-motion-19/prepared-current')))
pytestmark = pytest.mark.skipif(
    not all((PREPARED/name/'package.json').exists()
            for name in ['syntelle', 'cafe', 'woodland']),
    reason='Bounded local integration checks require cached neck preparation; no assets are generated by tests.')


def load(name):
    root = PREPARED/name
    package = json.loads((root/'package.json').read_text())
    rig = package['projection']
    raw = (root/'projection.bin').read_bytes()
    vertices = np.frombuffer(raw, '<f4', count=rig['geometry']['vertices']*5).reshape(-1, 5)
    indices = np.frombuffer(raw, '<u2', count=rig['geometry']['triangles']*3, offset=vertices.size*4)
    attributes = np.frombuffer(raw, '<f4', offset=rig['articulation']['attributes']['offset_bytes']).reshape(-1, 6)
    return package, vertices, indices, attributes


def test_three_source_bound_rigs_preserve_neutral_and_pass_combined_envelope():
    for name in ['syntelle', 'cafe', 'woodland']:
        p, v, t, a = load(name)
        rig = p['projection']; neck = rig['articulation']
        neutral, _ = project(v, a, rig['camera'], neck, [0, 0, 0])
        np.testing.assert_allclose(neutral, v[:, :2]*rig['camera']['size'], atol=1e-9)
        assert np.all(a[:, :3] >= 0) and np.all(a[:, :3].sum(1) <= 1.00001)
        assert validate(v, a, t, rig['camera'], neck, [3, 1.2, .3], p['anatomy']['face_height'])['valid']


def test_breathing_changes_depth_and_visible_torso_without_deforming_face():
    for name in ['syntelle', 'cafe', 'woodland']:
        p, v, _, a = load(name)
        rig = p['projection']; neck = rig['articulation']; camera = rig['camera']
        y = v[:, 1]*camera['size'][1]
        face = y <= p['anatomy']['chin_y']
        before, q0 = project(v, a, camera, neck, [0, 0, 0])
        after, q1 = project(v, a, camera, neck, [0, 0, 0], -p['anatomy']['face_height']*.006)
        np.testing.assert_array_equal(a[face, 3:], 0)
        np.testing.assert_array_equal(before[face], after[face])
        assert np.max(q0-q1) > 1
        assert np.max(np.linalg.norm((after-before)[a[:, 5] > .05], axis=1)) > .1


def test_face_is_one_rigid_transform_and_neck_influence_is_distributed():
    p, v, _, a = load('syntelle')
    rig = p['projection']; neck = rig['articulation']; camera = rig['camera']
    face = v[:, 1]*camera['size'][1] <= p['anatomy']['chin_y']
    np.testing.assert_array_equal(a[face, 0], 1)
    np.testing.assert_array_equal(a[face, 1:3], 0)
    assert np.count_nonzero(a[:, 1] > .3) > 5 and np.count_nonzero(a[:, 2] > .3) > 5
    # Recover deformed world points and check distances, independently of texture.
    original = unproject(v[face], camera)
    projected, q = project(v[face], a[face], camera, neck, [3, 1, .2])
    recovered = np.column_stack(((projected-camera['center'])*q[:, None]/camera['focal'], camera['distance']-q))
    np.testing.assert_allclose(np.linalg.norm(original[1:]-original[:-1], axis=1),
                               np.linalg.norm(recovered[1:]-recovered[:-1], axis=1), atol=1e-9)
